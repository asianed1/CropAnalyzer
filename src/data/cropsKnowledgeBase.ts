export interface FarmerContextInput {
  suspectedCropId: string; // 'auto' (Do not know) or one of the 30 crop IDs
  plantPart: PlantPart;
  primarySymptom: PrimarySymptom;
  growthStage: GrowthStage;
  fieldCondition: FieldCondition;
  soilMoisture: SoilMoisture;
  sunlightExposure: SunlightExposure;
  recentInputs: RecentInputHistory;
  notes?: string;
}

export interface ConditionRecommendation {
  immediateActions: string[];
  biologicalControl: string[];
  chemicalGuidance: string;
  prevention: string[];
}

export interface CropCondition {
  id: string;
  name: string;
  scientificName: string;
  category: ConditionCategory;
  affectedParts: PlantPart[];
  symptomTags: PrimarySymptom[];
  growthStages: GrowthStage[];
  weatherTriggers: FieldCondition[];
  summary: string;
  visualSignature: {
    dominantTrait:
      | 'brown_lesion'
      | 'gray_diamond'
      | 'orange_rust'
      | 'yellow_mosaic'
      | 'white_powder'
      | 'chewed_frass'
      | 'dark_rot'
      | 'healthy_green';
    minNecroticRatio?: number;
    minYellowRatio?: number;
    minRustRatio?: number;
    minGrayWhiteRatio?: number;
  };
  recommendations: ConditionRecommendation;
}

export interface AbioticCondition extends CropCondition {
  category: 'Abiotic';
  soilTriggers: SoilMoisture[];
  sunlightTriggers: SunlightExposure[];
  inputTriggers: RecentInputHistory[];
}

